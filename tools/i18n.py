def keys_of(path: str) -> dict[str, str]:
    text = open(path, encoding='utf-8').read()
    return dict(re.findall(r'^"([^"]+)"\s*=\s*"(.*)";\s*$', text, re.M))


def escape(value: str) -> str:
    return value.replace('\\', '\\\\').replace('"', '\\"')


def main() -> int:
    en_path = os.path.join(RES, 'en.lproj/Localizable.strings')
    en = keys_of(en_path)
    report_only = '--report' in sys.argv

    for lang, table in sorted(TRANSLATIONS.items()):
        target_dir = os.path.join(RES, f'{lang}.lproj')
        target_path = os.path.join(target_dir, 'Localizable.strings')
        existing = keys_of(target_path) if os.path.exists(target_path) else {}
        merged: dict[str, str] = {}
        for key, english in en.items():
            merged[key] = table.get(key) or existing.get(key) or english
        if report_only and existing == merged:
            continue
        os.makedirs(target_dir, exist_ok=True)
        with open(target_path, 'w', encoding='utf-8') as handle:
            handle.write(f'/* NetCove — {lang} */\n\n')
            for key in en:
                handle.write(f'"{key}" = "{escape(merged[key])}";\n')

    for lang in ['en'] + sorted(TRANSLATIONS):
        path = os.path.join(RES, f'{lang}.lproj/Localizable.strings')
        table = keys_of(path)
        translated = sum(1 for k, v in table.items() if v and v != en.get(k))
        print(f'{lang:8} keys={len(table):3}  translated={translated:3}  fallback={len(table) - translated:3}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
